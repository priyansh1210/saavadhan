CAP = {"scam": 4, "warn": 3, "nowarn": 2, "safe": 3}


def expand(lang: str, label: str, template: str, k: int) -> list[str]:
    d = L[lang]
    slots = re.findall(r"{(\w+)}", template)
    if not slots:
        return [template, d["hi"][k % 2] + template]
    out = []
    for i in range(CAP[label]):
        # each slot moves through its list at a different pace, so combinations vary
        vals = {s: d[s][(i * (j + 1) + k) % len(d[s])] for j, s in enumerate(dict.fromkeys(slots))}
        sentence = template.format(**vals)
        if sentence not in out:
            out.append(sentence)
    return out


def cases() -> list[tuple[str, str, str]]:
    """(language, sentence, label) for every generated sentence."""
    out = []
    for lang, d in L.items():
        for label in ("scam", "warn", "nowarn", "safe"):
            for k, t in enumerate(d[label]):
                out += [(lang, s, label) for s in expand(lang, label, t, k)]
    return out


